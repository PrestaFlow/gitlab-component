#!/usr/bin/env bash
# comment-mr.sh — Post or update a Merge Request note with the run summary.
# Mirrors src/reporter/pr-comment*.ts:
#   - same marker patterns  → find and update the previous note in place
#   - same body layout       → success vs failure, per-suite table, failure details
#
# Auth: MR notes cannot be created with CI_JOB_TOKEN. The consumer must
# provide GITLAB_TOKEN as a masked CI variable (project or personal access
# token with the api scope).
set -euo pipefail

# --- decide whether to post at all -------------------------------------------

# Auto default = true on MR pipelines, false otherwise.
DEFAULT="false"
if [ -n "${CI_MERGE_REQUEST_IID:-}" ]; then DEFAULT="true"; fi

MODE="${PRESTAFLOW_MR_COMMENT:-}"
if [ -z "$MODE" ]; then MODE="$DEFAULT"; fi

if [ "$MODE" != "true" ]; then
  echo "comment-mr: disabled (mr_comment=$MODE) — skipping"
  exit 0
fi

if [ -z "${CI_MERGE_REQUEST_IID:-}" ]; then
  echo "comment-mr: not a merge-request pipeline — skipping"
  exit 0
fi

GITLAB_API_URL="${CI_API_V4_URL:-https://gitlab.com/api/v4}"
PROJECT_ID="${CI_MERGE_REQUEST_PROJECT_ID:-${CI_PROJECT_ID:-}}"
MR_IID="${CI_MERGE_REQUEST_IID}"

if [ -z "${GITLAB_TOKEN:-}" ]; then
  echo "comment-mr: GITLAB_TOKEN is not set. CI_JOB_TOKEN cannot post MR notes."
  echo "comment-mr:   Add a masked CI variable GITLAB_TOKEN (personal or project access token, api scope)."
  echo "comment-mr:   Skipping (this is a warning, not a failure)."
  exit 0
fi

# --- locate results.json -----------------------------------------------------

RESULTS=""
for c in tests/prestaflow/results.json prestaflow/results.json; do
  if [ -f "$c" ]; then RESULTS="$c"; break; fi
done

# --- pull the report url/id from upload.sh's dotenv (best-effort) ------------

REPORT_URL=""
REPORT_ID=""
if [ -f prestaflow.env ]; then
  # shellcheck disable=SC1091
  . prestaflow.env || true
  REPORT_URL="${PRESTAFLOW_REPORT_URL:-}"
  REPORT_ID="${PRESTAFLOW_REPORT_ID:-}"
fi

# --- compute report stats via jq --------------------------------------------
# Aggregates the same fields that src/reporter/parse-results.ts does.

if [ -n "$RESULTS" ]; then
  STATS_JSON=$(jq '
    def tonum(x): (x // 0 | tonumber? // 0);
    def sfrom(s):
      { name: (s.suite // ""),
        passed: (s.stats.passes | tonum(.)),
        failed: (s.stats.failures | tonum(.)),
        skipped: ((s.stats.skips | tonum(.)) + (s.stats.skippeds | tonum(.))),
        todos: (s.stats.todos | tonum(.)),
        durationMs: (s.stats.time | tonum(.)),
        failures: [ (s.tests // [])[] | select(.state == "fail") | {
          suite: (s.suite // ""),
          title: (.title // ""),
          message: ((.expect.fail // [])[0] // ""),
          file: (.file // ""),
          line: (.line | tonum(.))
        }]
      };
    if type == "object" and (.suites | type == "array") then
      [ .suites[] | sfrom(.) ]
    elif type == "object" and (.stats) then
      [ sfrom(.) ]
    else
      []
    end
    | { suites: [ .[] | {name, passed, failed, skipped, durationMs} ],
        failures: [ .[].failures[] ],
        passed: [.[].passed] | add // 0,
        failed: [.[].failed] | add // 0,
        skipped: [.[].skipped] | add // 0,
        todos: [.[].todos] | add // 0,
        durationMs: [.[].durationMs] | add // 0 }
    | .total = (.passed + .failed + .skipped + .todos)
  ' "$RESULTS")
else
  STATS_JSON='{"suites":[],"failures":[],"passed":0,"failed":0,"skipped":0,"todos":0,"durationMs":0,"total":0}'
fi

PASSED=$(echo "$STATS_JSON" | jq -r '.passed')
FAILED=$(echo "$STATS_JSON" | jq -r '.failed')
SKIPPED=$(echo "$STATS_JSON" | jq -r '.skipped')
TOTAL=$(echo "$STATS_JSON" | jq -r '.total')
DURATION_MS=$(echo "$STATS_JSON" | jq -r '.durationMs')

format_duration() {
  local ms="$1"
  local s=$(( (ms + 500) / 1000 ))
  if [ $s -lt 60 ]; then echo "${s}s"; return; fi
  local m=$(( s / 60 )); local r=$(( s % 60 ))
  printf "%dm %02ds" "$m" "$r"
}

DURATION_HUMAN=$(format_duration "$DURATION_MS")

# --- marker (same shape as pr-comment-body.ts) ------------------------------

PROJECT_KEY="${PRESTAFLOW_PROJECT_ID:-}"
if [ -z "$PROJECT_KEY" ]; then
  MARKER='<!-- prestaflow-report -->'
else
  MARKER="<!-- prestaflow-run:${PROJECT_KEY} -->"
fi

# --- build body --------------------------------------------------------------

SHORT_SHA=$(printf '%s' "${CI_COMMIT_SHA:-}" | cut -c1-7)
FOOTER="<sub>Generated by [PrestaFlow/gitlab-component](https://github.com/PrestaFlow/gitlab-component) · commit \`${SHORT_SHA}\`</sub>"

META_PARTS=()
if [ -n "${PRESTAFLOW_SUITES:-}" ]; then
  # backtick-quote each suite
  QUOTED=$(printf '%s' "$PRESTAFLOW_SUITES" | awk -F, '{for(i=1;i<=NF;i++){gsub(/^[ \t]+|[ \t]+$/,"",$i); if($i!="") printf "%s`%s`", (i>1?", ":""), $i}}')
  META_PARTS+=("Suites: $QUOTED")
fi
if [ "${PRESTAFLOW_FLASHLIGHT:-false}" = "true" ] && [ -n "${PRESTAFLOW_PS_VERSION:-}" ]; then
  META_PARTS+=("PS \`${PRESTAFLOW_PS_VERSION}\`")
fi
META_LINE=""
if [ ${#META_PARTS[@]} -gt 0 ]; then
  META_LINE=$(printf ' · %s' "${META_PARTS[@]}"); META_LINE="${META_LINE:3}"
fi

# per-suite table (only when >1 suite)
SUITE_TABLE=""
SUITE_COUNT=$(echo "$STATS_JSON" | jq -r '.suites | length')
if [ "$SUITE_COUNT" -gt 1 ]; then
  ROWS=$(echo "$STATS_JSON" | jq -r --arg dur "" '
    .suites[] |
    "| " + .name + " | " + (.passed|tostring) + " | " + (.failed|tostring) + " | " + (.durationMs|tostring) + "ms |"')
  # Rewrite the raw ms into human duration in bash (jq lacks time-formatting).
  HUMAN_ROWS=""
  while IFS= read -r row; do
    ms=$(echo "$row" | awk -F' \\| ' '{gsub("ms \\|","",$5); print $5}')
    hum=$(format_duration "${ms:-0}")
    HUMAN_ROWS+="${row/${ms}ms |/${hum} |}\n"
  done <<< "$ROWS"
  SUITE_TABLE="| Suite | ✔ Passed | ✘ Failed | Duration |
|-------|:--------:|:--------:|:--------:|
$(printf '%b' "$HUMAN_ROWS")"
fi

if [ "$FAILED" = "0" ]; then
  # ---- success body ----
  BODY="$MARKER
### PrestaFlow — Test report ✅

**${TOTAL} tests passed in ${DURATION_HUMAN}**
"
  [ -n "$SUITE_TABLE" ] && BODY="${BODY}
${SUITE_TABLE}
"
  [ -n "$META_LINE" ] && BODY="${BODY}
${META_LINE}
"
  [ -n "$REPORT_URL" ] && BODY="${BODY}
📊 [View full report](${REPORT_URL})
"
  BODY="${BODY}
${FOOTER}"
else
  # ---- failure body ----
  MAX_FAILURES=20
  FAILURE_COUNT=$(echo "$STATS_JSON" | jq -r '.failures | length')
  EXTRA=$(( FAILURE_COUNT - MAX_FAILURES )); [ $EXTRA -lt 0 ] && EXTRA=0

  FAILURE_DETAILS=$(echo "$STATS_JSON" | jq -r --argjson max "$MAX_FAILURES" '
    .failures[:$max] | map(
      "**❌ " + .suite + " / " + .title + "**\n> " +
      (if (.message | length) > 200 then (.message[0:200] + "…") else .message end) +
      (if .file != "" then ("\n> `" + .file + ":" + (.line|tostring) + "`") else "" end)
    ) | join("\n\n")')
  if [ "$EXTRA" -gt 0 ]; then
    FAILURE_DETAILS="${FAILURE_DETAILS}

… +${EXTRA} more failed. View full run for the complete list."
  fi

  BODY="$MARKER
### PrestaFlow — Test report

**Result: ❌ ${FAILED} failures out of ${TOTAL} tests**

| Passed | Failed | Skipped | Duration |
|--------|--------|---------|----------|
| ${PASSED} ✅ | ${FAILED} ❌ | ${SKIPPED} ⏭️ | ${DURATION_HUMAN} |
"
  [ -n "$SUITE_TABLE" ] && BODY="${BODY}
${SUITE_TABLE}
"
  [ -n "$META_LINE" ] && BODY="${BODY}
${META_LINE}
"
  BODY="${BODY}
<details>
<summary>Failure details (${FAILED})</summary>

${FAILURE_DETAILS}

</details>
"
  [ -n "$REPORT_URL" ] && BODY="${BODY}
📊 [View full report](${REPORT_URL})
"
  BODY="${BODY}
${FOOTER}"
fi

# --- find existing note (paginated, up to 5 pages of 100) -------------------

find_existing_note_id() {
  local page
  for page in 1 2 3 4 5; do
    local notes
    notes=$(curl -sS -H "PRIVATE-TOKEN: ${GITLAB_TOKEN}" \
      "${GITLAB_API_URL}/projects/${PROJECT_ID}/merge_requests/${MR_IID}/notes?per_page=100&page=${page}") || return 0
    local id
    id=$(echo "$notes" | jq -r --arg m1 '<!-- prestaflow-run:' --arg m2 '<!-- prestaflow-report -->' '
      map(select((.body // "") | (startswith($m1) or startswith($m2)))) | .[0].id // empty')
    if [ -n "$id" ]; then echo "$id"; return 0; fi
    local len; len=$(echo "$notes" | jq -r 'length // 0')
    if [ "$len" -lt 100 ]; then return 0; fi
  done
}

EXISTING=$(find_existing_note_id || true)

# Body must go through as JSON — use jq to encode it safely.
PAYLOAD=$(jq -n --arg body "$BODY" '{body: $body}')

if [ -n "$EXISTING" ]; then
  echo "comment-mr: updating existing note #$EXISTING"
  curl -sS -X PUT \
    -H "PRIVATE-TOKEN: ${GITLAB_TOKEN}" \
    -H "Content-Type: application/json" \
    -d "$PAYLOAD" \
    "${GITLAB_API_URL}/projects/${PROJECT_ID}/merge_requests/${MR_IID}/notes/${EXISTING}" \
    -o /dev/null -w 'http=%{http_code}\n'
else
  echo "comment-mr: creating new note on MR !${MR_IID}"
  curl -sS -X POST \
    -H "PRIVATE-TOKEN: ${GITLAB_TOKEN}" \
    -H "Content-Type: application/json" \
    -d "$PAYLOAD" \
    "${GITLAB_API_URL}/projects/${PROJECT_ID}/merge_requests/${MR_IID}/notes" \
    -o /dev/null -w 'http=%{http_code}\n'
fi
